const PDFDocument = require('pdfkit');

function money(n) {
  return `Rs. ${Number(n || 0).toFixed(2)}`;
}

function drawHeader(doc, settings, title) {
  doc.fontSize(18).fillColor('#1a3d7c').text(settings.companyName || 'HR Warehouse', 50, 50);
  doc.fontSize(9).fillColor('#444444');
  if (settings.companyAddress) doc.text(settings.companyAddress, 50, 72, { width: 300 });
  if (settings.companyGstin) doc.text(`GSTIN: ${settings.companyGstin}`, 50, 86);
  if (settings.companyPhone) doc.text(`Phone: ${settings.companyPhone}`, 50, 98);
  if (settings.companyEmail) doc.text(`Email: ${settings.companyEmail}`, 50, 110);

  doc.fontSize(16).fillColor('#1a3d7c').text(title, 300, 50, { align: 'right', width: 245 });
  doc.moveTo(50, 130).lineTo(545, 130).strokeColor('#1a3d7c').lineWidth(1).stroke();
  doc.fillColor('#000000');
}

function drawFooter(doc, text) {
  const bottom = doc.page.height - 60;
  doc.fontSize(8).fillColor('#888888').text(text || 'Generated by HR Warehouse ERP', 50, bottom, { align: 'center', width: 495 });
}

function streamPdf(res, filename) {
  const doc = new PDFDocument({ margin: 50, size: 'A4' });
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `inline; filename="${filename}"`);
  doc.pipe(res);
  return doc;
}

function drawTable(doc, startY, columns, rows) {
  let y = startY;
  doc.fontSize(9).font('Helvetica-Bold');
  let x = 50;
  columns.forEach((col) => {
    doc.text(col.label, x, y, { width: col.width, align: col.align || 'left' });
    x += col.width;
  });
  y += 16;
  doc.moveTo(50, y).lineTo(545, y).strokeColor('#cccccc').stroke();
  y += 6;
  doc.font('Helvetica');

  rows.forEach((row) => {
    x = 50;
    columns.forEach((col) => {
      doc.text(String(row[col.key] ?? ''), x, y, { width: col.width, align: col.align || 'left' });
      x += col.width;
    });
    y += 18;
  });
  return y;
}

function generateInvoicePdf(res, invoice, settings) {
  const doc = streamPdf(res, `${invoice.invoiceNumber}.pdf`);
  drawHeader(doc, settings, invoice.type === 'Quotation' ? 'QUOTATION' : 'TAX INVOICE');

  doc.fontSize(10);
  doc.text(`${invoice.type} No: ${invoice.invoiceNumber}`, 50, 145);
  doc.text(`Date: ${new Date(invoice.invoiceDate).toLocaleDateString()}`, 50, 160);
  if (invoice.dueDate) doc.text(`Due: ${new Date(invoice.dueDate).toLocaleDateString()}`, 50, 175);

  doc.font('Helvetica-Bold').text('Bill To:', 320, 145);
  doc.font('Helvetica');
  doc.text(invoice.buyerSnapshot?.name || '', 320, 160);
  if (invoice.buyerSnapshot?.address) doc.text(invoice.buyerSnapshot.address, 320, 174, { width: 225 });
  if (invoice.buyerSnapshot?.gstin) doc.text(`GSTIN: ${invoice.buyerSnapshot.gstin}`, 320, 206);
  if (invoice.buyerSnapshot?.phone) doc.text(`Phone: ${invoice.buyerSnapshot.phone}`, 320, 220);

  let y = drawTable(
    doc,
    245,
    [
      { key: 'description', label: 'Description', width: 160 },
      { key: 'quantity', label: 'Qty', width: 40, align: 'right' },
      { key: 'unitPrice', label: 'Unit Price', width: 80, align: 'right' },
      { key: 'discount', label: 'Discount', width: 70, align: 'right' },
      { key: 'gstPercent', label: 'GST %', width: 50, align: 'right' },
      { key: 'lineTotal', label: 'Total', width: 95, align: 'right' },
    ],
    invoice.lineItems.map((li) => ({
      description: `${li.description}${li.sku ? ` (${li.sku})` : ''}`,
      quantity: li.quantity,
      unitPrice: money(li.unitPrice),
      discount: money(li.discount),
      gstPercent: `${li.gstPercent}%`,
      lineTotal: money(li.lineTotal),
    }))
  );

  y += 10;
  doc.moveTo(350, y).lineTo(545, y).strokeColor('#cccccc').stroke();
  y += 10;
  const totalsRow = (label, value, bold) => {
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(10);
    doc.text(label, 350, y, { width: 100 });
    doc.text(value, 450, y, { width: 95, align: 'right' });
    y += 16;
  };
  totalsRow('Subtotal', money(invoice.subtotal));
  totalsRow('Discount', money(invoice.discountTotal));
  totalsRow('Taxable Amount', money(invoice.taxableAmount));
  totalsRow('GST', money(invoice.gstAmount));
  totalsRow('Grand Total', money(invoice.grandTotal), true);
  totalsRow('Amount Paid', money(invoice.amountPaid));
  totalsRow('Balance Due', money(invoice.grandTotal - invoice.amountPaid), true);

  y += 10;
  doc.font('Helvetica-Bold').fontSize(10).text(`Payment Status: ${invoice.paymentStatus}`, 50, y);

  y += 30;
  doc.font('Helvetica-Bold').text('Terms & Conditions:', 50, y);
  doc.font('Helvetica').fontSize(9).text(invoice.termsAndConditions || 'Goods once sold are not returnable. Payment due within the agreed terms.', 50, y + 14, { width: 495 });

  y += 70;
  doc.fontSize(9).text('Authorized Signatory', 400, y + 40, { width: 145, align: 'center' });
  doc.moveTo(400, y + 38).lineTo(545, y + 38).strokeColor('#000000').stroke();

  drawFooter(doc, `${settings.companyName} | This is a system-generated document.`);
  doc.end();
}

